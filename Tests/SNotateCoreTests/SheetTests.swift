import CoreGraphics
import Foundation
import ImageIO
import Testing
@testable import SNotateCore

struct SheetTests {
    private func options(_ change: (inout ExportOptions) -> Void) -> ExportOptions {
        var options = ExportOptions()
        change(&options)
        return options
    }

    private func url(_ annotated: AnnotatedCase, _ name: String) -> URL {
        annotated.folder.appendingPathComponent("notated/" + name)
    }

    @Test func theConfigTurnsThemOn() {
        let (config, issues) = SNotateConfig.parse("export_sheet both\nexport_typst on\nexport_sheet poster\ntypst_import memo:0.16\n")
        #expect(ExportOptions(config: config).sheet == .both)
        #expect(ExportOptions(config: config).typst)
        #expect(ExportOptions(config: config).typstImport == nil)
        #expect(issues.map(\.description) == [
            "line 3: export_sheet: 'poster' is not off, png, pdf or both",
            "line 4: typst_import: 'memo:0.16' is not none or a package such as @local/memo:1.0.0",
        ])
        let (named, none) = SNotateConfig.parse("typst_import @local/memo-kit:1.2.0\n")
        #expect(none.isEmpty)
        #expect(ExportOptions(config: named).typstImport == "@local/memo-kit:1.2.0")
        #expect(ExportOptions(config: SNotateConfig.parse("typst_import @local/memo:1.0.0\ntypst_import none\n").0).typstImport == nil)
    }

    @Test func captionsBecomeTypstMarkup() {
        #expect(TypstFragment.markup("Open **Actions** > **Migrate** on the VM") == "Open *Actions* \\> *Migrate* on the VM")
        #expect(TypstFragment.markup("IP 10.0.0.10 in #net_1 [admin] $5 @me ~x a/b") == "IP 10.0.0.10 in \\#net\\_1 \\[admin\\] \\$5 \\@me \\~x a\\/b")
        #expect(TypstFragment.markup("- not a list") == "\\- not a list")
        #expect(TypstFragment.markup("2 ** 3") == "2 \\*\\* 3")
    }

    @Test func theFragmentHasOneShotPerExportedStep() throws {
        let annotated = try AnnotatedCase()
        let document = try annotated.document()
        let files = document.steps.filter { !$0.excluded }.map(\.file)
        let text = TypstFragment.text(document, files: files, format: .png)
        let lines = text.components(separatedBy: "\n")
        #expect(lines[0].hasPrefix("// generated by sNotate from poc-sample-vm-migrate's sidecar and memo"))
        #expect(lines[3] == "#let shot(body, caption: none) = figure(body, caption: caption)")
        let imported = TypstFragment.text(document, files: [], format: .png, typstImport: "@local/memo:1.2.0")
        #expect(imported.components(separatedBy: "\n")[3] == "#import \"@local/memo:1.2.0\": shot")
        #expect(lines.filter { $0.hasPrefix("#shot(") }.count == 5)
        #expect(lines.contains("#shot(image(\"poc-sample-vm-migrate-01.png\"), caption: [Open *Actions* \\> *Migrate* on the VM])"))
        #expect(TypstFragment.text(document, files: [files[0]], format: .jpeg).contains("image(\"poc-sample-vm-migrate-00.jpg\")"))
    }

    @Test func exportWritesTheSheetAndFragmentOnceAndRemovesThemWhenOff() throws {
        let annotated = try AnnotatedCase()
        let document = try annotated.document()
        let all = options { $0.sheet = .both; $0.typst = true }
        let first = try Exporter.exportCase(document, options: all)
        let extras = ["notated/poc-sample-vm-migrate-sheet.png", "notated/poc-sample-vm-migrate-sheet.pdf", "notated/poc-sample-vm-migrate.typ"]
        #expect(extras.allSatisfy(first.written.contains))
        #expect(ContactSheet.recordedFingerprint(at: url(annotated, "poc-sample-vm-migrate-sheet.pdf")) != nil)
        let second = try Exporter.exportCase(document, options: all)
        #expect(second.written.isEmpty)
        #expect(extras.allSatisfy(second.unchanged.contains))
        let sheet = try #require(Renderer.loadImage(at: url(annotated, "poc-sample-vm-migrate-sheet.png")))
        try Golden.check(sheet, "sheet")
        let third = try Exporter.exportCase(document)
        #expect(extras.allSatisfy(third.removed.contains))
        #expect(!FileManager.default.fileExists(atPath: url(annotated, "poc-sample-vm-migrate.typ").path))
    }

    @Test func filesThatAreNotOursAreLeftAlone() throws {
        let annotated = try AnnotatedCase()
        let folder = annotated.folder.appendingPathComponent("notated")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        try Data("// my own fragment\n".utf8).write(to: folder.appendingPathComponent("poc-sample-vm-migrate.typ"))
        try Data("%PDF-1.4 not ours".utf8).write(to: folder.appendingPathComponent("poc-sample-vm-migrate-sheet.pdf"))
        let report = try Exporter.exportCase(try annotated.document())
        #expect(!report.removed.contains { $0.hasSuffix(".typ") || $0.hasSuffix(".pdf") })
        #expect(FileManager.default.fileExists(atPath: folder.appendingPathComponent("poc-sample-vm-migrate.typ").path))
    }

    @Test func aChangedCaseRewritesThePDF() throws {
        let annotated = try AnnotatedCase()
        var document = try annotated.document()
        let pdfOnly = options { $0.sheet = .pdf }
        _ = try Exporter.exportCase(document, options: pdfOnly)
        let before = ContactSheet.recordedFingerprint(at: url(annotated, "poc-sample-vm-migrate-sheet.pdf"))
        #expect(!FileManager.default.fileExists(atPath: url(annotated, "poc-sample-vm-migrate-sheet.png").path))
        document.sidecar.steps[0].items.removeAll()
        let report = try Exporter.exportCase(document, options: pdfOnly)
        #expect(report.written.contains("notated/poc-sample-vm-migrate-sheet.pdf"))
        #expect(ContactSheet.recordedFingerprint(at: url(annotated, "poc-sample-vm-migrate-sheet.pdf")) != before)
    }
}
