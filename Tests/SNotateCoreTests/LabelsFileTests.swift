import Foundation
import Testing
@testable import SNotateCore

struct LabelsFileTests {
    private func notated(_ annotated: AnnotatedCase, _ name: String) -> URL {
        annotated.folder.appendingPathComponent("notated/" + name)
    }

    private func read(_ url: URL) throws -> String {
        try String(contentsOf: url, encoding: .utf8)
    }

    private let exported = (0...4).map(AnnotatedCase.file)

    @Test func theMarkdownIsTheEvidenceScriptsMemoAfterItsHeaderLine() throws {
        let annotated = try AnnotatedCase()
        let document = try annotated.document()
        let text = LabelsFile.text(.markdown, document, files: exported, format: .png)
        let header = "<!-- generated by sNotate from \(AnnotatedCase.name)'s sidecar and memo; export again rather than edit. -->\n\n"
        #expect(text.hasPrefix(header))
        // The fixture memo is in the script's shape with every caption filled
        // in; step 05 is excluded, so its block is the only difference.
        let memo = try #require(document.memo).removingReferences(to: AnnotatedCase.file(5)).memo
        #expect(String(text.dropFirst(header.count)) == String(decoding: memo.bytes, as: UTF8.self))
    }

    @Test func theYAMLListsEachStepWithItsCaption() throws {
        let annotated = try AnnotatedCase()
        let text = LabelsFile.text(.yaml, try annotated.document(), files: Array(exported.prefix(2)), format: .jpeg)
        #expect(text == """
            # generated by sNotate from \(AnnotatedCase.name)'s sidecar and memo; export again rather than edit.
            case: "\(AnnotatedCase.name)"
            steps:
              - n: 1
                file: "\(AnnotatedCase.name)-00.jpg"
                source: "\(AnnotatedCase.file(0))"
                caption: "Open the VM list and pick the running VM to migrate"
              - n: 2
                file: "\(AnnotatedCase.name)-01.jpg"
                source: "\(AnnotatedCase.file(1))"
                caption: "Open **Actions** > **Migrate** on the VM"

            """)
    }

    @Test func noCaptionIsTheScriptsPlaceholderAndAssetsKeepTheirFolder() throws {
        let temp = try TempFolder()
        try temp.file("poc-x-y/poc-x-y-00.png")
        try temp.file("poc-x-y/assets/scap (1).png")
        let document = try CaseDocument.load(folder: temp.url.appendingPathComponent("poc-x-y"))
        let files = document.steps.map(\.file)
        let markdown = LabelsFile.text(.markdown, document, files: files, format: .jpeg)
        #expect(markdown.hasSuffix("""
            # poc-x-y

            - description

            ![poc-x-y-00](poc-x-y-00.jpg)

            - description

            ![scap (1)](<assets/scap (1).jpg>)

            """))
        #expect(Memo.imagePaths(in: "![scap (1)](<assets/scap (1).jpg>)") == ["assets/scap (1).jpg"])
        let yaml = LabelsFile.text(.yaml, document, files: [], format: .png)
        #expect(yaml.hasSuffix("case: \"poc-x-y\"\nsteps: []\n"))
    }

    @Test func captionsAreQuotedForYAML() {
        #expect(LabelsFile.quoted("plain") == "\"plain\"")
        #expect(LabelsFile.quoted("- Say \"yes\": #1 \\ done\t") == "\"- Say \\\"yes\\\": #1 \\\\ done\\t\"")
        #expect(LabelsFile.quoted("Bước 2\u{07}") == "\"Bước 2\\x07\"")
    }

    @Test func exportWritesBothOnceAndTheConfigChoosesThem() throws {
        let annotated = try AnnotatedCase()
        let document = try annotated.document()
        let first = try Exporter.exportCase(document)
        #expect(first.written.suffix(2) == ["md", "yaml"].map { "notated/\(AnnotatedCase.name).\($0)" })
        #expect(try read(notated(annotated, "\(AnnotatedCase.name).md")).contains("- The task list shows the migration running"))
        let second = try Exporter.exportCase(document)
        #expect(second.written.isEmpty)

        var mdOnly = ExportOptions()
        mdOnly.labels = .md
        let third = try Exporter.exportCase(document, options: mdOnly)
        #expect(third.removed == ["notated/\(AnnotatedCase.name).yaml"])
        #expect(FileManager.default.fileExists(atPath: notated(annotated, "\(AnnotatedCase.name).md").path))
    }

    @Test func aFileOfTheSameNameThatIsNotOursIsLeftAlone() throws {
        let annotated = try AnnotatedCase()
        try FileManager.default.createDirectory(at: notated(annotated, ""), withIntermediateDirectories: true)
        let own = "# my own notes\n"
        try own.write(to: notated(annotated, "\(AnnotatedCase.name).md"), atomically: true, encoding: .utf8)
        var off = ExportOptions()
        off.labels = .off
        let report = try Exporter.exportCase(try annotated.document(), options: off)
        #expect(report.removed.isEmpty)
        #expect(try read(notated(annotated, "\(AnnotatedCase.name).md")) == own)
    }

    @Test func theConfigKey() {
        #expect(SNotateConfig().exportLabels == .both)
        let (config, issues) = SNotateConfig.parse("export_labels yaml\nexport_labels json\n")
        #expect(ExportOptions(config: config).labels == .yaml)
        #expect(ExportOptions.Labels.yaml.includes(.yaml))
        #expect(!ExportOptions.Labels.yaml.includes(.markdown))
        #expect(ExportOptions.Labels.both.includes(.markdown))
        #expect(issues.map(\.description) == ["line 2: export_labels: 'json' is not off, md, yaml or both"])
    }
}
