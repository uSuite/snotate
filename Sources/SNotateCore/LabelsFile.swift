import Foundation

/// SN-407: the exported steps' labels beside the images in `notated/`, as
/// `<case-id>.md` in the evidence memo shape (`# <case-id>`, then
/// a `- <caption>` bullet and its `![<stem>](<file>)` per step) and as
/// `<case-id>.yaml` for scripts. Paths are relative to `notated/`, in story
/// order, excluded steps left out; a step without a caption gets the
/// script's `description` placeholder in the memo and `""` in the YAML.
/// Beside the captures `<case-id>.md` is the evidence memo, so these files
/// never go there, as with the Typst fragment (DECISIONS 2026-10-29).
public enum LabelsFile {
    public enum Kind: String, Sendable, CaseIterable {
        case markdown = "md"
        case yaml

        public var fileExtension: String { rawValue }

        /// The first line's start, by which export knows the file is its own.
        var header: String {
            self == .markdown ? "<!-- generated by sNotate" : "# generated by sNotate"
        }
    }

    public static func text(
        _ kind: Kind,
        _ document: CaseDocument,
        files: [String],
        format: ExportOptions.Format
    ) -> String {
        let note = " from \(document.caseID)'s sidecar and memo; export again rather than edit."
        switch kind {
        case .markdown:
            var lines = [
                kind.header + note + " -->",
                "",
                "# \(document.caseID)",
                "",
            ]
            for file in files {
                let path = ExportPlan.outputPath(for: file, format: format)
                let caption = document.caption(for: file)
                let stem = ((path as NSString).lastPathComponent as NSString).deletingPathExtension
                lines += [
                    "- " + (caption.isEmpty ? Memo.placeholder : caption),
                    "",
                    "![\(stem)](\(link(path)))",
                    "",
                ]
            }
            return lines.joined(separator: "\n")
        case .yaml:
            var lines = [
                kind.header + note,
                "case: \(quoted(document.caseID))",
                files.isEmpty ? "steps: []" : "steps:",
            ]
            for (index, file) in files.enumerated() {
                lines += [
                    "  - n: \(index + 1)",
                    "    file: \(quoted(ExportPlan.outputPath(for: file, format: format)))",
                    "    source: \(quoted(file))",
                    "    caption: \(quoted(document.caption(for: file)))",
                ]
            }
            return lines.joined(separator: "\n") + "\n"
        }
    }

    /// A Markdown link target, in angle brackets when a space or a
    /// parenthesis would end it early.
    static func link(_ path: String) -> String {
        path.contains(where: { " ()".contains($0) }) ? "<\(path)>" : path
    }

    /// A YAML double-quoted scalar, so no caption is read as a number, a
    /// list, a comment or a mapping.
    static func quoted(_ text: String) -> String {
        var result = "\""
        for scalar in text.unicodeScalars {
            switch scalar {
            case "\\":
                result += "\\\\"
            case "\"":
                result += "\\\""
            case "\t":
                result += "\\t"
            case "\n":
                result += "\\n"
            case "\r":
                result += "\\r"
            default:
                if scalar.value < 0x20 || scalar.value == 0x7F {
                    result += String(format: "\\x%02X", scalar.value)
                } else {
                    result.unicodeScalars.append(scalar)
                }
            }
        }
        return result + "\""
    }

    static func isOurs(
        _ kind: Kind,
        at url: URL
    ) -> Bool {
        (try? String(contentsOf: url, encoding: .utf8))?.hasPrefix(kind.header) ?? false
    }
}
