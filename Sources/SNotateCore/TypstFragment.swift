import Foundation

/// SN-404: `notated/<case-id>.typ`, one `#shot` per exported step with its
/// caption, for a Typst memo. A memo includes it with
/// `#include "notated/<case-id>.typ"`; Typst evaluates an included file as
/// its own module, so the fragment brings `shot` itself: imported from the
/// package named by `typst_import`, or, by default, defined as a plain
/// `figure`. It has no `#show`, so the memo's styling applies. `#shot` takes the image
/// itself, and the paths are relative to `notated/`, where the fragment and
/// the images both live. Beside the captures `<case-id>.typ` is the evidence
/// script's Typst memo, so the fragment never goes there (DECISIONS
/// 2026-10-27).
public enum TypstFragment {
    /// The first line, by which export knows the file is its own.
    static let header = "// generated by sNotate"

    public static func text(
        _ document: CaseDocument,
        files: [String],
        format: ExportOptions.Format,
        typstImport: String? = nil
    ) -> String {
        var lines = [
            "\(header) from \(document.caseID)'s sidecar and memo; export again rather than edit.",
            "// Include it from a Typst memo:",
            "//   #include \"notated/\(document.caseID).typ\"",
            typstImport.map { "#import \"\($0)\": shot" }
                ?? "#let shot(body, caption: none) = figure(body, caption: caption)",
            "",
        ]
        for file in files {
            let path = ExportPlan.outputPath(for: file, format: format)
            let caption = document.caption(for: file)
            lines.append(caption.isEmpty
                ? "#shot(image(\"\(path)\"))"
                : "#shot(image(\"\(path)\"), caption: [\(markup(caption))])")
        }
        return lines.joined(separator: "\n") + "\n"
    }

    /// The caption as Typst markup: `**bold**` becomes `*bold*`, and
    /// everything Typst would read as markup is escaped, including a list
    /// or heading marker at the start.
    static func markup(_ caption: String) -> String {
        let parts = caption.components(separatedBy: "**")
        let paired = parts.count % 2 == 1
        var result = ""
        for (index, part) in parts.enumerated() {
            if index > 0 {
                result += paired ? "*" : "\\*\\*"
            }
            result += escape(part)
        }
        if let first = result.first, "-+=".contains(first) {
            result = "\\" + result
        }
        return result
    }

    static func escape(_ text: String) -> String {
        var escaped = ""
        for character in text {
            if "\\#*_`$@<>[]~/".contains(character) {
                escaped.append("\\")
            }
            escaped.append(character)
        }
        return escaped
    }

    static func isOurs(_ url: URL) -> Bool {
        (try? String(contentsOf: url, encoding: .utf8))?.hasPrefix(header) ?? false
    }
}
